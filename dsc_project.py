# 3. Probability Distribution for each model
plt.figure(figsize=(18, 6))

for i, (name, model) in enumerate(models.items(), 1):
    if hasattr(model, 'predict_proba'):
        plt.subplot(1, 3, i)
        probs = model.predict_proba(X_test)[:, 1]

        # Separate probabilities for actual fraud and non-fraud cases
        fraud_probs = probs[y_test == 1]
        non_fraud_probs = probs[y_test == 0]

        # Plot distributions
        plt.hist(non_fraud_probs, bins=50, alpha=0.5, label='Not Fraud', color='blue')
        plt.hist(fraud_probs, bins=50, alpha=0.5, label='Fraud', color='red')
        plt.xlabel('Predicted Probability of Fraud')
        plt.ylabel('Count')
        plt.title(f'{name} - Probability Distribution')
        plt.legend()

plt.tight_layout()
